-- =====================================================================
-- Q22 · 「占总流水百分比」为什么分母要写成子查询
-- 王自强 · 2026-09-23 · 库：practice · 表：retail_clean
-- =====================================================================
-- 说明：本文件 6 段实验，全部是 SELECT，不含任何破坏性语句。
--       建议一段一段跑，先看结果再看下一段。
-- =====================================================================


-- ─────────────────────────────────────────────────────────────────────
-- 实验 A · 证明「两个 SUM 都指向当前这一组」→ 相除恒等于 1
-- 预期：5 行的「自己除自己」全部 = 1.0000
-- ─────────────────────────────────────────────────────────────────────
SELECT country,
       ROUND(SUM(amount), 2)              AS 本组流水,
       ROUND(SUM(amount) / SUM(amount), 4) AS 自己除自己
FROM retail_clean
GROUP BY country
ORDER BY 本组流水 DESC
LIMIT 5;

-- 看懂这一句，就明白为什么不能偷懒写 SUM(amount)/SUM(amount)：
-- 两个 SUM 都在「当前这一组」里 → 分子分母是同一个数 → 结果永远是 100%。


-- ─────────────────────────────────────────────────────────────────────
-- 实验 B · 那能不能写 SUM(SUM(amount))？不能 —— 会直接报错
-- 预期：ERROR 1111 (HY000): Invalid use of group function
-- 这就是「必须另开子查询」的官方理由：聚合函数不能嵌套。
-- ─────────────────────────────────────────────────────────────────────
SELECT country, SUM(SUM(amount)) AS 想当然的写法
FROM retail_clean
GROUP BY country;


-- ─────────────────────────────────────────────────────────────────────
-- 实验 C · Q22 原写法（子查询版）
-- 预期第一行：United Kingdom | 14,389,234.92 | 5350 | 82.82
-- ─────────────────────────────────────────────────────────────────────
SELECT country,
       ROUND(SUM(amount), 2) AS revenue,
       COUNT(DISTINCT customer_id) AS customers,
       ROUND(SUM(amount) * 100.0 / (SELECT SUM(amount) FROM retail_clean), 2) AS pct
FROM retail_clean
GROUP BY country
ORDER BY revenue DESC
LIMIT 10;

-- 关键：括号里那条子查询是「另开一条查询」，它和外层的 GROUP BY 没有关系，
--       只返回一个孤零零的数（17,374,804.27）。这个数对每一行都是同一个常数。


-- ─────────────────────────────────────────────────────────────────────
-- 实验 D · 等价写法：把总数用 CROSS JOIN 变成一列
-- 预期：与实验 C 的输出逐行完全一致
-- ⚠️ 派生表必须写别名 t，引用时必须写 t.total —— 不写别名会报 1248
-- ─────────────────────────────────────────────────────────────────────
SELECT r.country,
       ROUND(SUM(r.amount), 2) AS revenue,
       ROUND(SUM(r.amount) * 100.0 / t.total, 2) AS pct
FROM retail_clean AS r
CROSS JOIN (SELECT SUM(amount) AS total FROM retail_clean) AS t
GROUP BY r.country
ORDER BY revenue DESC
LIMIT 10;


-- ─────────────────────────────────────────────────────────────────────
-- 实验 E · 手算对账（把你算出来的百分比倒推回去验证）
-- 预期：82.8170...
-- 结论：14,389,234.92 ÷ 17,374,804.27 = 0.8282 → 82.82% ✔ 闭合
-- ─────────────────────────────────────────────────────────────────────
SELECT 14389234.92 / 17374804.27 * 100 AS 手算英国占比;


-- ─────────────────────────────────────────────────────────────────────
-- 实验 F · 关于 100.0 那个小数点
-- 预期：用100 和 用100点0 两列结果相同（都是 82.82）
--
-- 原因是 MySQL 的除法运算符 / 天生返回小数，不做整除截断，
-- 所以在这台库里写 100 或 100.0 结果一样。
-- 保留 100.0 的价值在于：① 换到 SQL Server 等会整除截断的库不踩坑
--                        ② 阅读的人一眼看出这是百分比
--
-- ⚠️ 顺带演示一个要点：子查询是独立的，不受外层 WHERE 影响。
--    外层加了 WHERE country='United Kingdom'，括号里那条仍然是全表总额。
-- ─────────────────────────────────────────────────────────────────────
SELECT ROUND(SUM(amount) * 100   / (SELECT SUM(amount) FROM retail_clean), 2) AS 用100,
       ROUND(SUM(amount) * 100.0 / (SELECT SUM(amount) FROM retail_clean), 2) AS 用100点0
FROM retail_clean
WHERE country = 'United Kingdom';


-- ─────────────────────────────────────────────────────────────────────
-- 附 · 一个必然被追问的问题：这 10 个国家的 pct 加起来是 100% 吗？
-- 答案：不是，是 97.11%。
-- 因为 LIMIT 10 只取了前 10 名，剩下的 30 多个国家合计只占 2.89%。
-- ★ 这句话本身就是业务结论：这家公司的收入高度集中，
--   前 10 个国家就吃掉 97%，长尾几乎可以忽略。
-- ─────────────────────────────────────────────────────────────────────
SELECT ROUND(SUM(pct), 2) AS 前10合计占比
FROM (
    SELECT ROUND(SUM(amount) * 100.0 / (SELECT SUM(amount) FROM retail_clean), 2) AS pct
    FROM retail_clean
    GROUP BY country
    ORDER BY SUM(amount) DESC
    LIMIT 10
) AS top10;
